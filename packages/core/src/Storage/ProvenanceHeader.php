<?php

declare(strict_types=1);

namespace TestPilot\Storage;

/**
 * Writes and reads the provenance block at the top of every generated test file.
 * The "@testpilot-generated" marker is what allows TestPilot to overwrite a file; files without it
 * are treated as developer-owned and are never touched.
 */
final class ProvenanceHeader
{
    public const MARKER = '@testpilot-generated';

    /** @param array<string, scalar|null> $fields */
    public static function apply(string $code, array $fields): string
    {
        $code = self::strip($code);
        $lines = ['/**', ' * ' . self::MARKER, ' *'];
        foreach ($fields as $key => $value) {
            if ($value === null || $value === '') {
                continue;
            }
            $value = str_replace(['*/', "\n"], ['* /', ' '], (string) (is_bool($value) ? ($value ? 'true' : 'false') : $value));
            $lines[] = sprintf(' * %-14s %s', $key . ':', $value);
        }
        $lines[] = ' *';
        $lines[] = ' * Generated by TestPilot AI. Review before editing; edits are kept but marked human-modified.';
        $lines[] = ' */';

        $block = implode("\n", $lines);
        $body = (string) preg_replace('/^<\?php\s*/', '', $code);

        if (preg_match('/^(declare\s*\(\s*strict_types\s*=\s*1\s*\)\s*;)\s*/', $body, $m) === 1) {
            return "<?php\n\n{$m[1]}\n\n{$block}\n\n" . ltrim(substr($body, strlen($m[0])));
        }

        return "<?php\n\n{$block}\n\n" . ltrim($body);
    }

    /** @return array<string, string> */
    public static function read(string $code): array
    {
        if (! self::isGenerated($code)) {
            return [];
        }

        preg_match('#/\*\*.*?' . preg_quote(self::MARKER, '#') . '.*?\*/#s', $code, $block);
        $fields = [];
        foreach (explode("\n", $block[0] ?? '') as $line) {
            if (preg_match('/^\s*\*\s+([a-z][a-z0-9_-]*):\s+(.+)$/i', $line, $m) === 1) {
                $fields[$m[1]] = trim($m[2]);
            }
        }

        return $fields;
    }

    public static function isGenerated(string $code): bool
    {
        return str_contains($code, self::MARKER);
    }

    public static function strip(string $code): string
    {
        return (string) preg_replace('#/\*\*(?:(?!\*/).)*?' . preg_quote(self::MARKER, '#') . '.*?\*/\s*#s', '', $code, 1);
    }
}
