<?php

declare(strict_types=1);

use PhpParser\ParserFactory;
use TestPilot\Exceptions\InvalidAiResponseException;
use TestPilot\Fuzz\FuzzDatasetBuilder;
use TestPilot\Generation\CodeExtractor;
use TestPilot\Storage\ProvenanceHeader;
use TestPilot\Storage\TestFileWriter;
use TestPilot\Security\PathGuard;
use TestPilot\Exceptions\PolicyViolationException;

describe('FuzzDatasetBuilder', function () {
    it('is deterministic for a given seed', function () {
        $target = scanFixtures()->find('App\Services\InvoiceService::clamp');
        $builder = new FuzzDatasetBuilder();

        $a = $builder->build($target, 20, 48213);
        $b = $builder->build($target, 20, 48213);
        $c = $builder->build($target, 20, 1);

        expect($a['cases'])->toBe($b['cases'])->toHaveCount(20)
            ->and($a['cases'])->not->toBe($c['cases'])
            ->and($a['seed'])->toBe(48213);
    });

    it('starts with boundary values and includes null for nullable parameters', function () {
        $target = scanFixtures()->find('App\Support\money_round()');
        $dataset = (new FuzzDatasetBuilder())->build($target, 30, 7);

        $precisions = array_column($dataset['cases'], 'precision');
        expect($dataset['cases'][0])->toBe(['amount' => 0.0, 'precision' => 0])
            ->and($precisions)->toContain(null)
            ->and($precisions)->toContain(PHP_INT_MAX);
    });

    it('exports a dataset that is valid PHP', function () {
        $target = scanFixtures()->find(INVOICE);
        $dataset = (new FuzzDatasetBuilder())->build($target, 15, 3);

        $ast = (new ParserFactory())->createForNewestSupportedVersion()->parse('<?php return ' . $dataset['code'] . ';');

        expect($ast)->not->toBeEmpty()
            ->and($dataset['code'])->toContain("'case 1' => [");
    });
});

describe('CodeExtractor', function () {
    it('extracts a single php block', function () {
        expect(CodeExtractor::php("Here you go:\n```php\n<?php\n\nit('x', fn () => expect(1)->toBe(1));\n```\nThanks"))
            ->toStartWith('<?php')->toContain("it('x'");
    });

    it('rejects replies without a php file or with several', function (string $reply) {
        CodeExtractor::php($reply);
    })->with([
        'prose' => ['I cannot do that.'],
        'two files' => ["```php\n<?php echo 1;\n```\n```php\n<?php echo 2;\n```"],
    ])->throws(InvalidAiResponseException::class);
});

describe('ProvenanceHeader', function () {
    it('round-trips provenance fields after declare(strict_types=1)', function () {
        $code = ProvenanceHeader::apply("<?php\n\ndeclare(strict_types=1);\n\nit('a', fn () => null);\n", [
            'target' => 'A::b', 'model' => 'claude', 'fuzz-seed' => 42, 'empty' => null,
        ]);

        expect($code)->toStartWith("<?php\n\ndeclare(strict_types=1);\n\n/**\n * @testpilot-generated")
            ->and(ProvenanceHeader::read($code))->toBe(['target' => 'A::b', 'model' => 'claude', 'fuzz-seed' => '42'])
            ->and(substr_count(ProvenanceHeader::apply($code, ['target' => 'A::b']), ProvenanceHeader::MARKER))->toBe(1);
    });
});

describe('TestFileWriter', function () {
    it('moves an approved candidate into the generated test directory', function () {
        $root = temporaryDirectory();
        $writer = new TestFileWriter(new PathGuard($root));
        $target = scanFixtures()->find(INVOICE);

        $pending = $writer->writePending($writer->pendingPath($target), "<?php\n\nit('[S1] x', fn () => expect(1)->toBe(1));\n", ['target' => $target->key]);
        $approved = $writer->approve($pending, $writer->approvedPath($target), ['approved-by' => 'yash']);

        expect($pending)->toBe('storage/testpilot/pending/Unit/InvoiceServiceCalculateTotalTest.php')
            ->and($approved)->toBe('tests/TestPilot/Generated/Unit/InvoiceServiceCalculateTotalTest.php')
            ->and(is_file("{$root}/{$pending}"))->toBeFalse()
            ->and(ProvenanceHeader::read((string) file_get_contents("{$root}/{$approved}")))
            ->toMatchArray(['target' => $target->key, 'approved-by' => 'yash', 'status' => 'approved']);
    });

    it('never overwrites a developer-written test', function () {
        $root = temporaryDirectory();
        $writer = new TestFileWriter(new PathGuard($root));
        $target = scanFixtures()->find(INVOICE);
        mkdir("{$root}/tests/TestPilot/Generated/Unit", 0777, true);
        file_put_contents("{$root}/" . $writer->approvedPath($target), "<?php // hand written\n");

        $pending = $writer->writePending($writer->pendingPath($target), "<?php\n", []);
        $writer->approve($pending, $writer->approvedPath($target));
    })->throws(PolicyViolationException::class, 'not generated by TestPilot');

    it('refuses to write pending files outside the pending directory', function () {
        (new TestFileWriter(new PathGuard(temporaryDirectory())))->writePending('app/Evil.php', '<?php', []);
    })->throws(PolicyViolationException::class);
});
