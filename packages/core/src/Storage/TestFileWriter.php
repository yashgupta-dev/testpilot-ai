<?php

declare(strict_types=1);

namespace TestPilot\Storage;

use TestPilot\DTO\TargetType;
use TestPilot\DTO\TestTarget;
use TestPilot\Exceptions\PolicyViolationException;
use TestPilot\Security\PathGuard;

/**
 * The only component that writes test files. Writes are restricted to two directories:
 * the pending area (verified, not yet approved) and the generated-tests area (approved).
 */
final class TestFileWriter
{
    public function __construct(
        private readonly PathGuard $guard,
        private readonly string $generatedDirectory = 'tests/TestPilot/Generated',
        private readonly string $pendingDirectory = 'storage/testpilot/pending',
    ) {
    }

    public function fileName(TestTarget $target): string
    {
        $base = $target->type === TargetType::Function
            ? ucfirst((string) preg_replace('/[^A-Za-z0-9]/', '', ucwords(str_replace('_', ' ', (string) $target->function))))
            : $this->short((string) $target->class) . ucfirst((string) $target->method);

        return $base . 'Test.php';
    }

    /** Relative path of the candidate file for a target (one candidate per target at a time). */
    public function pendingPath(TestTarget $target, string $module = 'Unit'): string
    {
        return trim($this->pendingDirectory, '/') . '/' . $module . '/' . $this->fileName($target);
    }

    public function approvedPath(TestTarget $target, string $module = 'Unit'): string
    {
        return trim($this->generatedDirectory, '/') . '/' . $module . '/' . $this->fileName($target);
    }

    /** @param array<string, scalar|null> $provenance */
    public function writePending(string $relativePath, string $code, array $provenance): string
    {
        $absolute = $this->guard->resolveWritable($relativePath, [$this->pendingDirectory]);
        $this->ensureDirectory(dirname($absolute));
        file_put_contents($absolute, ProvenanceHeader::apply($code, $provenance), LOCK_EX);

        return $this->guard->relative($absolute);
    }

    /**
     * Moves an approved candidate into the test suite.
     *
     * @param array<string, scalar|null> $extraProvenance e.g. approved-by, approved-at
     */
    public function approve(string $pendingPath, string $approvedPath, array $extraProvenance = []): string
    {
        $source = $this->guard->resolveWritable($pendingPath, [$this->pendingDirectory]);
        $target = $this->guard->resolveWritable($approvedPath, [$this->generatedDirectory]);

        if (! is_file($source)) {
            throw new PolicyViolationException("Pending test not found: {$pendingPath}");
        }

        if (is_file($target) && ! ProvenanceHeader::isGenerated((string) file_get_contents($target))) {
            throw new PolicyViolationException("Refusing to overwrite {$approvedPath}: it was not generated by TestPilot.");
        }

        $code = (string) file_get_contents($source);
        $fields = [...ProvenanceHeader::read($code), ...$extraProvenance, 'status' => 'approved'];

        $this->ensureDirectory(dirname($target));
        file_put_contents($target, ProvenanceHeader::apply($code, $fields), LOCK_EX);
        unlink($source);

        return $this->guard->relative($target);
    }

    public function discard(string $pendingPath): void
    {
        $absolute = $this->guard->resolveWritable($pendingPath, [$this->pendingDirectory]);
        if (is_file($absolute)) {
            unlink($absolute);
        }
    }

    public function read(string $relativePath): ?string
    {
        $absolute = $this->guard->resolveInside($relativePath);

        return is_file($absolute) ? (string) file_get_contents($absolute) : null;
    }

    private function ensureDirectory(string $directory): void
    {
        if (! is_dir($directory) && ! mkdir($directory, 0775, true) && ! is_dir($directory)) {
            throw new PolicyViolationException("Could not create directory {$directory}");
        }
    }

    private function short(string $class): string
    {
        return str_contains($class, '\\') ? substr($class, (int) strrpos($class, '\\') + 1) : $class;
    }
}
